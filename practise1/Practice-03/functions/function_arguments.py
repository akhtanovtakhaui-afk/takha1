
def rectangle_area(w, h):
    print(w * h)

rectangle_area(3, 4)

def power(a, p=2):
    print(a ** p)

power(5)
power(2, 3)

def profile(name, age, city):
    print(name, age, city)

profile(age=18, name="Aruzhan", city="Almaty")

def order(item, qty, price):
    print(item, qty, qty * price)

order("burger", qty=2, price=1500)

def average(a, b, c, d):
    print((a + b + c + d) / 4)

average(1, 2, 3, 4)
